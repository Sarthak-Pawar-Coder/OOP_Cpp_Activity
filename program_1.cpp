#include <iostream>
using namespace std;

int main() {
    // Declare variables of different basic data types
    int roll = 101;          // Stores whole number
    char grade = 'A';        // Stores a single character
    float fee = 12500.50;    // Stores decimal number

    // Display the values
    cout << "Roll No: " << roll << endl;
    cout << "Grade: " << grade << endl;
    cout << "Fee: " << fee << endl;

    return 0; // End of program
}
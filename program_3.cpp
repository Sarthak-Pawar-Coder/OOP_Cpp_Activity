#include <iostream>
using namespace std;

int main() {
    // Create an array to store marks of 5 students
    int marks[5] = {78, 82, 91, 67, 88};

    // Loop through all array elements
    for (int i = 0; i < 5; i++) {
        cout << marks[i] << " ";
    }

    return 0; // End of program
}
